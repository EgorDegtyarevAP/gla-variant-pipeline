"""Stage 2. IN: data/interim/*.parquet. OUT: data/processed/variants_master.{parquet,csv},
results/tables/{excluded_or_unresolved.csv, legacy_v2_diff.csv}, docs/audit_report.md."""
import sys, pathlib, json; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src"))
import pandas as pd
from gla.common import INTERIM, PROCESSED, RESULTS, ROOT
from gla.harmonize import build_mapper, resolve_unparsed, build_master
from gla.hgvs import UTR5_LEN, UTR3_LEN
from gla.hgvs import norm_c

if __name__ == "__main__":
    PROCESSED.mkdir(parents=True, exist_ok=True); (RESULTS / "tables").mkdir(parents=True, exist_ok=True)
    cv, gn = pd.read_parquet(INTERIM / "clinvar.parquet"), pd.read_parquet(INTERIM / "gnomad.parquet")
    am, am_bad = pd.read_parquet(INTERIM / "amenability.parquet"), pd.read_parquet(INTERIM / "amenability_unresolved.parquet")
    unp = pd.read_parquet(INTERIM / "clinvar_unparsed.parquet"); gmeta = json.loads((INTERIM / "gnomad_meta.json").read_text())

    mp, n_snv, bad = build_mapper(gn)
    d5, d3 = UTR5_LEN, UTR3_LEN
    unp_res = resolve_unparsed(unp, cv, mp, d5, d3)
    M, aud = build_master(cv, gn, am, unp_res)
    M.to_parquet(PROCESSED / "variants_master.parquet"); M.to_csv(PROCESSED / "variants_master.csv", index=False)

    # ---- excluded / unresolved registry (nothing is dropped silently)
    reg = pd.concat([
        am_bad.assign(source="amicus")[["source", "amicus_id", "amicus_legacy_nt", "amicus_protein_raw", "amenability_status", "reason"]],
        aud["clinvar_unresolved"].assign(source="clinvar", reason="hgvs_c_unparseable (repeat notation / empty)"),
        unp_res[unp_res.status != "mapped"].assign(source="clinvar_unparsed", reason=lambda d: d.status),
    ], ignore_index=True)
    reg.to_csv(RESULTS / "tables" / "excluded_or_unresolved.csv", index=False)

    # ---- cross-source integrity: gnomAD's own ClinVar IDs vs ClinVar file keys
    link = gn.dropna(subset=["gnomad_clinvar_id"]).copy(); link["gnomad_clinvar_id"] = link.gnomad_clinvar_id.astype(int)
    cvmap = cv.dropna(subset=["hgvs_c"]).set_index("clinvar_id").hgvs_c
    link["cv_key"] = link.gnomad_clinvar_id.map(cvmap)
    id_missing = link.cv_key.isna().sum(); id_disagree = ((link.cv_key.notna()) & (link.cv_key != link.hgvs_c)).sum()

    # ---- legacy comparison
    leg = pd.read_csv(ROOT / "data/legacy/GLA_final_merged_v2.csv", dtype=str)
    leg["hgvs_c"] = leg["c.change"].map(norm_c)
    lk = set(leg.hgvs_c.dropna()); nk = set(M.hgvs_c)
    lm = leg.dropna(subset=["hgvs_c"]).drop_duplicates("hgvs_c").merge(M[["hgvs_c", "amenability_status"]], on="hgvs_c", suffixes=("_legacy", "_new"))
    lm["amenability_status_legacy"] = lm.amenability_status_legacy.replace("not_in_amenability_table", pd.NA)
    status_diff = lm[lm.amenability_status_legacy.fillna("NA") != lm.amenability_status_new.fillna("NA")]
    pd.concat([pd.DataFrame({"hgvs_c": sorted(lk - nk), "where": "only_in_legacy_v2"}),
               pd.DataFrame({"hgvs_c": sorted(nk - lk), "where": "only_in_new_master"})]).to_csv(RESULTS / "tables" / "legacy_v2_diff.csv", index=False)
    status_diff[["hgvs_c", "amenability_status_legacy", "amenability_status_new"]].to_csv(RESULTS / "tables" / "legacy_v2_status_diff.csv", index=False)

    # ---- report
    vc = M.variant_class.value_counts()
    ov = M.sources.value_counts()
    R = []
    R.append("# Audit report: variants_master (auto-generated by scripts/05_harmonize.py)\n")
    R.append("## 1. Inputs and parse yield\n")
    R.append(f"| source | rows in file | used | note |\n|---|---|---|---|\n"
             f"| ClinVar export | {len(cv)} | {cv.hgvs_c.notna().sum()} parsed c. | {cv.hgvs_c.isna().sum()} unparsed (repeat notation or empty c.) |\n"
             f"| ClinVar genomic-only names | {len(unp)} | {(unp_res.status=='mapped').sum()} mapped into transcript | {(unp_res.status=='outside_transcript_extent').sum()} outside the mRNA (flank), {(unp_res.status.str.startswith('unresolved')).sum()} non-SNV unresolved |\n"
             f"| gnomAD v4.1.1 | {gmeta['rows_total']} | {gmeta['rows_canonical']} canonical-transcript rows | {gmeta['rows_other_transcripts']} rows on non-canonical transcripts dropped ({gmeta['other_transcripts']}) |\n"
             f"| Amicus table | 2192 | 2123 rows -> {len(am)} nucleotide changes | 69 rows on the user's exclusion list (multi-locus, compound codon, large rearrangements, unlocalised) |\n")
    R.append("Literature table: not provided, not included.\n")
    R.append("## 2. Genomic-to-c. mapper\n")
    R.append(f"Derived from gnomAD canonical SNVs (exon offsets by majority vote; vote purity per exon: {', '.join(f'{x:.2f}' for x in mp.vote_purity)}). "
             f"Reproduces {n_snv - len(bad)}/{n_snv} gnomAD SNV names. Caveat: offsets are fitted on the same rows, so this checks internal consistency "
             f"(intron nearest-rule, strand handling, UTR numbering), not an independent reference. Re-check against NM_000169 FASTA when supplied.\n")
    R.append("ClinVar genomic-only names:\n\n" + unp_res.to_markdown(index=False) + "\n")
    R.append(f"Transcript extent (NM_000169.3 GenBank): c.-{d5} .. c.*{d3}; variants outside it are upstream/downstream flank. Unparsed ClinVar names outside it and absent from the export are not added to the master.\n")
    R.append("## 2b. Reference checks (NM_000169.3 GenBank)\n")
    R.append(f"SNVs with a reference-base check possible (CDS, c.-22..-1, c.*1..*6): {int(M.ref_ok.notna().sum())}; **mismatching: {int(M.ref_ok.eq(False).sum())}**. "
             f"CDS translation equals the GenBank translation (429 aa); exon ends from the record (c.194/369/547/639/801/999) equal the boundaries used for IVS conversion.\n")
    if len(aud["ref_mismatch"]):
        R.append(aud["ref_mismatch"].to_markdown(index=False) + "\n")
    R.append("## 3. Overlap of sources (rows in variants_master)\n")
    R.append(ov.to_frame("n").to_markdown() + f"\n\nTotal unique variants: **{len(M)}**.\n")
    R.append("## 4. Integrity checks\n")
    R.append(f"- gnomAD rows carrying a ClinVar Variation ID: {len(link)}; ID absent from the ClinVar export: {id_missing}; ID present but c. key differs: **{id_disagree}**\n"
             f"- duplicate keys inside ClinVar: {aud['clinvar_dup_keys']}; inside gnomAD canonical: {aud['gnomad_dup_keys']}\n"
             f"- Amicus keys with conflicting amenability status: **{len(aud['amicus_conflicts'])}**\n"
             f"- keys where sources disagree on the protein change: **{len(aud['protein_conflicts'])}**\n")
    if len(aud["protein_conflicts"]):
        R.append(aud["protein_conflicts"].head(30).to_markdown(index=False) + "\n")
    if len(aud["amicus_conflicts"]):
        R.append(aud["amicus_conflicts"].to_markdown(index=False) + "\n")
    R.append("## 5. Variant classes and samples\n")
    R.append(vc.to_frame("n").to_markdown() + "\n")
    R.append(f"| sample | n |\n|---|---|\n| S_all | {int(M.S_all.sum())} |\n| S_mis | {int(M.S_mis.sum())} |\n| S_amen | {int(M.S_amen.sum())} |\n| S_path | {int(M.S_path.sum())} |\n")
    R.append("S_amen split: " + M[M.S_amen].amenability_status.value_counts().to_dict().__repr__() + "\n")
    R.append("Amenability status counts (all classes): " + M.amenability_status.value_counts(dropna=False).to_dict().__repr__() + "\n")
    R.append("`cds_snv_unannotated` = exonic SNV without a protein change in any source; resolved at stage 3 once the CDS is supplied.\n")
    R.append("## 6. Comparison with legacy GLA_final_merged_v2.csv (cross-check only, not an input)\n")
    R.append(f"- legacy unique parsed keys: {len(lk)}; new master: {len(nk)}; only in legacy: {len(lk-nk)}; only in new: {len(nk-lk)}\n"
             f"- on shared keys, amenability status differs in {len(status_diff)} of {len(lm)} (legacy 'not_in_amenability_table' treated as NA); see results/tables/legacy_v2_status_diff.csv\n")
    R.append("## 7. Excluded or unresolved records\n")
    R.append(reg.groupby(["source", "reason"]).size().to_frame("n").to_markdown() + "\n\nFull list: results/tables/excluded_or_unresolved.csv\n")
    (ROOT / "docs" / "audit_report.md").write_text("\n".join(R))
    print("master", M.shape, "\n", vc.to_string(), "\n", ov.to_string(), "\nlegacy only/new only", len(lk - nk), len(nk - lk), "status diff", len(status_diff), "/", len(lm))
