"""Stage 6 (levels 1-2). IN: processed/variants_master, features_structural, results/tables/cpg_*.csv.
OUT: results/tables/stats_A..E_*.csv and docs/stats_report.md. Plan: docs/stats_plan.md."""
import sys, pathlib; sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1] / "src"))
import numpy as np, pandas as pd
from scipy.stats import mannwhitneyu
from gla.common import PROCESSED, RESULTS, ROOT, load_config
from gla import stats as st

T = RESULTS / "tables"
cfg = load_config()["stats"]; B = cfg["permutations"]; SEED = cfg["random_seed"]
BURIED = 0.2
def fmt(d):
    d = d.copy()
    for c in d.columns:
        if c.startswith(("p_", "q_")) or c in ("p", "p_local", "p_fwer"):
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else f"{v:.2e}")
    return d.round(4).to_markdown(index=False)

def structural():
    S = pd.read_parquet(PROCESSED / "features_structural.parquet")
    S["buried"] = S.rsa < BURIED
    return S

def pos_of(protein):
    return protein.str.extract(r"(\d+)")[0].astype(int)

if __name__ == "__main__":
    M = pd.read_parquet(PROCESSED / "variants_master.parquet"); S = structural(); R = S[S.structure_resolved].set_index("protein_pos")
    Pm = pd.read_csv(T / "cpg_possible_snvs.csv"); Pm["pos"] = (Pm.c_pos - 1) // 3 + 1
    rep = ["# Statistics report, levels 1-2 (auto-generated by scripts/10_stats.py; plan: docs/stats_plan.md)\n",
           "Read every table with its ascertainment in mind: ClinVar = clinically reported variants, gnomAD = population, Amicus = in-vitro tested substitutions. "
           "Counts are numbers of distinct variants (or protein changes / positions as stated), not patients.\n"]

    # ---------------- A: amenable vs non-amenable
    a = M[M.S_amen].drop_duplicates("protein")[["protein", "amenability_status"]].copy()
    a["pos"] = pos_of(a.protein); a = a[a.pos.isin(R.index)].reset_index(drop=True)
    y = (a.amenability_status == "non_amenable").to_numpy()
    upos = np.sort(a.pos.unique()); idx = np.searchsorted(upos, a.pos.to_numpy())
    rows = []
    feats = [("rsa", "cont"), ("dist_ligand", "cont"), ("dsasa_interface", "cont"),
             ("buried", "bin"), ("active_site", "bin"), ("interface", "bin"), ("glyco_site", "bin")]
    for f, kind in feats:
        fp = R.loc[upos, f].to_numpy(float)
        stat = st.auc if kind == "cont" else st._prop_diff
        rng = np.random.default_rng(SEED)
        obs, p = st.cluster_permutation(idx, y, fp, stat, B, rng)
        lo, hi = st.cluster_bootstrap_ci(idx, y, fp, stat, 2000, np.random.default_rng(SEED + 1))
        x = fp[idx]
        rows.append({"feature": f, "type": kind, "n_non_amenable": int(y.sum()), "n_amenable": int((~y).sum()),
                     "stat": "AUC(non>amen)" if kind == "cont" else "diff_prop(non-amen)", "estimate": obs, "ci95_low": lo, "ci95_high": hi,
                     "mean_or_prop_non": x[y].mean(), "mean_or_prop_amen": x[~y].mean(),
                     "median_non": np.median(x[y]) if kind == "cont" else np.nan, "median_amen": np.median(x[~y]) if kind == "cont" else np.nan,
                     "p_cluster_perm": p})
    A = pd.DataFrame(rows); A["q_BH"] = st.bh(A.p_cluster_perm)
    sens = []                                               # sensitivity of the burial threshold (not in the BH family)
    for thr in (0.1, 0.3):
        fp = (R.loc[upos, "rsa"] < thr).to_numpy(float)
        obs, p = st.cluster_permutation(idx, y, fp, st._prop_diff, 2000, np.random.default_rng(SEED))
        sens.append({"feature": f"buried_rsa<{thr}", "estimate": obs, "p_cluster_perm(2000)": p})
    A.to_csv(T / "stats_A_amenable_vs_nonamenable.csv", index=False)
    rep += ["## A. Amenable vs non-amenable (unique protein changes, clustered by position)\n",
            f"n = {len(a)} protein changes at {len(upos)} positions ({int((~y).sum())} amenable, {int(y.sum())} non-amenable). Unit-of-analysis note: features are constant within a position, so the null permutes positions.\n",
            fmt(A.drop(columns=["type"])), "\nBurial-threshold sensitivity:\n", fmt(pd.DataFrame(sens))]

    # ---------------- B: positions with P/LP missense / gnomAD missense vs other resolved positions
    plp_pos = set(pos_of(M[M.S_path].protein)); gn = M[(M.variant_class == "missense") & M.in_gnomad & M.gnomad_pass.fillna(False)]
    gn_pos = set(pos_of(gn.protein))
    rowsB = []
    for name, grp in (("ClinVar P/LP missense (S_path)", plp_pos), ("gnomAD PASS missense", gn_pos)):
        inn = R.index.isin(grp)
        for f, kind in feats:
            x = R[f].to_numpy(float)
            if kind == "cont":
                u = mannwhitneyu(x[inn], x[~inn]); auc_ = u.statistic / (inn.sum() * (~inn).sum())
                rowsB.append({"group": name, "feature": f, "n_pos_in": int(inn.sum()), "n_pos_out": int((~inn).sum()),
                              "stat": "AUC(in>out)", "estimate": auc_, "median_in": np.median(x[inn]), "median_out": np.median(x[~inn]), "p": u.pvalue})
            else:
                k1, n1, k0, n0 = int(x[inn].sum()), int(inn.sum()), int(x[~inn].sum()), int((~inn).sum())
                o, lo, hi, p = st.fisher_or(k1, n1 - k1, k0, n0 - k0)
                rowsB.append({"group": name, "feature": f, "n_pos_in": n1, "n_pos_out": n0, "stat": "OR", "estimate": o, "ci95_low": lo,
                              "ci95_high": hi, "prop_in": k1 / n1, "prop_out": k0 / n0, "p": p})
    Bt = pd.DataFrame(rowsB); Bt["q_BH"] = Bt.groupby("group").p.transform(lambda s: st.bh(s.to_numpy()))
    Bt.to_csv(T / "stats_B_position_level.csv", index=False)
    rep += ["\n## B. Position-level: positions carrying variants vs all other resolved positions\n",
            f"universe = {len(R)} resolved positions (32-422); S_path positions {len(plp_pos & set(R.index))}, gnomAD missense positions {len(gn_pos & set(R.index))}.\n", fmt(Bt)]

    # ---------------- C: structural category of S_path variants
    sp = M[M.S_path][["hgvs_c", "protein", "amenability_status"]].copy(); sp["pos"] = pos_of(sp.protein)
    def cat(p):
        if p not in R.index: return "no_structure"
        r = R.loc[p]
        if r.active_site: return "active_site"
        if r.interface: return "dimer_interface"
        if r.glyco_site: return "glycosylation_Asn"
        return "buried_core" if r.buried else "surface"
    sp["category"] = sp.pos.map(cat); R["category"] = [cat(p) for p in R.index]
    rowsC = []
    for c, g in sp.groupby("category"):
        k, n = len(g), len(sp); lo, hi = st.wilson(k, n); base = (R.category == c).mean() if c != "no_structure" else np.nan
        known = g.amenability_status.notna(); nn = (g.amenability_status == "non_amenable").sum()
        l2, h2 = st.wilson(nn, known.sum())
        rowsC.append({"category": c, "n_S_path": k, "frac_S_path": k / n, "ci95_low": lo, "ci95_high": hi, "frac_of_all_resolved_positions": base,
                      "n_with_status": int(known.sum()), "n_non_amenable": int(nn), "frac_non_amenable": nn / known.sum() if known.sum() else np.nan,
                      "ci95_low_nonamen": l2, "ci95_high_nonamen": h2})
    C = pd.DataFrame(rowsC).sort_values("n_S_path", ascending=False); C.to_csv(T / "stats_C_S_path_categories.csv", index=False)
    rep += ["\n## C. Structural category of ClinVar P/LP missense (priority: active site > interface > glycosylation > core > surface)\n", fmt(C)]

    # ---------------- D: migalastat coverage ceiling among ClinVar P/LP
    plp = M[M.clinvar_class.isin(["P", "LP", "P/LP"])]
    rowsD = []
    N = len(plp)
    for c, g in plp.groupby("variant_class"):
        lo, hi = st.wilson(len(g), N); rowsD.append({"scope": "ClinVar P/LP by class", "class": c, "n": len(g), "frac_of_P/LP": len(g) / N, "ci95_low": lo, "ci95_high": hi})
    mis = plp[plp.variant_class == "missense"]; nm = len(mis)
    for lab, mask in (("amenable", mis.amenability_status == "amenable"), ("non_amenable", mis.amenability_status == "non_amenable"), ("not_in_table(NA)", mis.amenability_status.isna())):
        lo, hi = st.wilson(int(mask.sum()), nm); rowsD.append({"scope": "ClinVar P/LP missense by Amicus status", "class": lab, "n": int(mask.sum()), "frac_of_P/LP": mask.sum() / nm, "ci95_low": lo, "ci95_high": hi})
    am_n, na_n = int((mis.amenability_status == "amenable").sum()), int(mis.amenability_status.isna().sum())
    for lab, k in (("lower bound (amenable / all P/LP)", am_n), ("upper bound ((amenable + NA) / all P/LP)", am_n + na_n)):
        lo, hi = st.wilson(k, N); rowsD.append({"scope": "migalastat coverage of ALL ClinVar P/LP (denominator incl. non-missense)", "class": lab, "n": k, "frac_of_P/LP": k / N, "ci95_low": lo, "ci95_high": hi})
    D = pd.DataFrame(rowsD); D.to_csv(T / "stats_D_coverage.csv", index=False)
    rep += ["\n## D. Migalastat coverage ceiling among ClinVar P/LP\n", f"denominator: {N} ClinVar P/LP variants in the master table. Coverage is limited by the Amicus table (in-vitro HEK-293-type criterion, see amenability_criterion); NA = not in the table, shown as bounds.\n", fmt(D)]

    # ---------------- E: regional clustering (window scan) + profile
    W = cfg.get("window", 20)
    poss = Pm[Pm.consequence == "missense"]; counts = np.bincount(poss.pos, minlength=430).astype(float)
    rowsE, regions = [], []
    scans = {"P/LP missense (S_path)": M[M.S_path], "S_path non-amenable": M[M.S_path & (M.amenability_status == "non_amenable")],
             "S_path amenable": M[M.S_path & (M.amenability_status == "amenable")]}
    for name, d in scans.items():
        d = d[d.hgvs_c.isin(set(poss.hgvs_c))]; p_ = pos_of(d.protein).to_numpy()
        w = st.window_scan(p_, counts, W, B, np.random.default_rng(SEED)); w.insert(0, "sample", name); w["n_variants"] = len(d)
        rowsE.append(w)
        sig = w[w.p_fwer < 0.05]
        if len(sig):                                    # merge overlapping significant windows
            cur = [sig.iloc[0].start, sig.iloc[0].end]
            for r in sig.iloc[1:].itertuples():
                if r.start <= cur[1] + 1: cur[1] = max(cur[1], r.end)
                else: regions.append({"sample": name, "start": cur[0], "end": cur[1]}); cur = [r.start, r.end]
            regions.append({"sample": name, "start": cur[0], "end": cur[1]})
    E = pd.concat(rowsE); E.to_csv(T / "stats_E_windows.csv", index=False)
    Rg = pd.DataFrame(regions)
    if len(Rg):
        Rg["n_observed"] = [int(((pos_of(scans[r.sample].protein) >= r.start) & (pos_of(scans[r.sample].protein) <= r.end)).sum()) for r in Rg.itertuples()]
        Rg["n_expected"] = [len(scans[r.sample][scans[r.sample].hgvs_c.isin(set(poss.hgvs_c))]) * counts[r.start:r.end + 1].sum() / counts.sum() for r in Rg.itertuples()]
    Rg.to_csv(T / "stats_E_regions.csv", index=False)
    prof = pd.DataFrame({"pos": np.arange(1, 430)}); prof["bin"] = (prof.pos - 1) // 20
    sp2 = M[M.S_path].assign(pos=lambda d: pos_of(d.protein))
    prof = prof.merge(pd.DataFrame({"pos": np.arange(1, 430), "possible_missense": counts[1:]}), on="pos")
    prof["S_path"] = prof.pos.map(sp2.pos.value_counts()).fillna(0)
    for s_ in ("amenable", "non_amenable"):
        prof[f"S_path_{s_}"] = prof.pos.map(sp2[sp2.amenability_status == s_].pos.value_counts()).fillna(0)
    prof["rsa"] = prof.pos.map(R.rsa)
    binned = prof.groupby("bin").agg(first=("pos", "min"), last=("pos", "max"), possible_missense=("possible_missense", "sum"), S_path=("S_path", "sum"),
                                     S_path_amenable=("S_path_amenable", "sum"), S_path_non_amenable=("S_path_non_amenable", "sum"), mean_rsa=("rsa", "mean"))
    binned["S_path_per_possible_SNV"] = binned.S_path / binned.possible_missense
    binned.to_csv(T / "stats_E_profile_20aa_bins.csv")
    rep += [f"\n## E. Regional clustering (window = {W} aa; family-wise p by max-statistic permutation)\n",
            "Regions with family-wise p < 0.05 (merged windows):\n", fmt(Rg) if len(Rg) else "none\n", "\n20-aa profile: results/tables/stats_E_profile_20aa_bins.csv\n"]

    # ---------------- level 3: conservation
    Cn = pd.read_parquet(PROCESSED / "features_conservation.parquet").set_index("protein_pos")
    Sub = pd.read_parquet(PROCESSED / "features_substitution.parquet").set_index("protein")
    Cv = Cn[Cn.valid]
    a3 = a[a.pos.isin(Cv.index)].reset_index(drop=True)
    y3 = (a3.amenability_status == "non_amenable").to_numpy(); upos3 = np.sort(a3.pos.unique()); idx3 = np.searchsorted(upos3, a3.pos.to_numpy())
    rows3 = []
    for f, lvl in (("conservation", "position"), ("frac_human_aa", "position"), ("blosum62", "variant"), ("freq_alt_orthologs", "variant"), ("alt_seen", "variant")):
        binary = f == "alt_seen"; stat = st._prop_diff if binary else st.auc
        if lvl == "position":
            fp = Cv.loc[upos3, f].to_numpy(float); xv = fp[idx3]
            obs, p = st.cluster_permutation(idx3, y3, fp, stat, B, np.random.default_rng(SEED))
            lo, hi = st.cluster_bootstrap_ci(idx3, y3, fp, stat, 2000, np.random.default_rng(SEED + 1))
        else:
            xv = a3.protein.map(Sub[f]).to_numpy(float)
            obs, p = st.within_cluster_permutation(idx3, y3, xv, stat, 2000, np.random.default_rng(SEED))
            lo = hi = np.nan
        rows3.append({"feature": f, "unit_of_feature": lvl, "n_non_amenable": int(y3.sum()), "n_amenable": int((~y3).sum()),
                      "stat": "diff_prop(non-amen)" if binary else "AUC(non>amen)", "estimate": obs, "ci95_low": lo, "ci95_high": hi,
                      "mean_non": np.nanmean(xv[y3]), "mean_amen": np.nanmean(xv[~y3]), "p_perm": p})
    A3 = pd.DataFrame(rows3); A3["q_BH"] = st.bh(A3.p_perm); A3.to_csv(T / "stats_A3_conservation.csv", index=False)
    rep += ["\n## Level 3 (conservation) - A3. Amenable vs non-amenable\n",
            f"{len(a3)} protein changes at {len(upos3)} positions with >= {load_config()['conservation']['min_nongap_weight']:.0%} ortholog coverage. Position-level features: position-clustered permutation (10 000) + cluster bootstrap CI; substitution-level features (BLOSUM62, ortholog frequency of the alternative residue): labels permuted within position (2 000).\n",
            fmt(A3)]
    rowsB3 = []
    gn_valid = gn_pos & set(Cv.index)
    for name, grp in (("ClinVar P/LP missense (S_path)", plp_pos), ("gnomAD PASS missense", gn_pos)):
        inn = Cv.index.isin(grp)
        for f in ("conservation", "frac_human_aa"):
            x = Cv[f].to_numpy(float); u = mannwhitneyu(x[inn], x[~inn])
            rowsB3.append({"group": name, "feature": f, "n_pos_in": int(inn.sum()), "n_pos_out": int((~inn).sum()), "AUC(in>out)": u.statistic / (inn.sum() * (~inn).sum()),
                           "median_in": np.median(x[inn]), "median_out": np.median(x[~inn]), "p": u.pvalue})
    B3 = pd.DataFrame(rowsB3); B3["q_BH"] = st.bh(B3.p.to_numpy()); B3.to_csv(T / "stats_B3_position_conservation.csv", index=False)
    rep += ["\n## Level 3 - B3. Position-level: positions with variants vs other valid positions\n", fmt(B3)]
    # F: heterogeneity in the two senses of 'non-conserved'
    cnt_plp = pd.Series(pos_of(M[M.S_path].protein)).value_counts()
    Fd = Cv.copy(); Fd["n_plp"] = Fd.index.map(cnt_plp).fillna(0).astype(int); Fd["has_plp"] = Fd.n_plp > 0
    Fd["quartile"] = pd.qcut(Fd.conservation.rank(method="first"), 4, labels=["Q1 (least conserved)", "Q2", "Q3", "Q4 (most conserved)"])
    qa = a3.assign(q=a3.pos.map(Fd.quartile))
    Ftab = Fd.groupby("quartile", observed=True).agg(positions=("n_plp", "size"), positions_with_PLP=("has_plp", "sum"), PLP_variants=("n_plp", "sum"),
                                                     conservation_min=("conservation", "min"), conservation_max=("conservation", "max")).reset_index()
    Ftab["frac_positions_with_PLP"] = Ftab.positions_with_PLP / Ftab.positions
    Ftab["non_amenable_share_S_amen"] = Ftab.quartile.map(qa.groupby("q", observed=True).amenability_status.apply(lambda s: (s == "non_amenable").mean()))
    Ftab["n_S_amen"] = Ftab.quartile.map(qa.groupby("q", observed=True).size())
    from scipy.stats import spearmanr
    rho, pr = spearmanr(Fd.conservation, Fd.n_plp)
    Ftab.to_csv(T / "stats_F_conservation_quartiles.csv", index=False)
    glob = pd.DataFrame([
        {"quantity": "valid positions (ortholog coverage >= threshold)", "value": len(Cv), "note": f"of 429; kept orthologs: {int((pd.read_csv(T / 'conservation_qc.csv').status == 'kept').sum())}"},
        {"quantity": "median conservation (1 - H/log2 20), weighted", "value": Cv.conservation.median(), "note": "unweighted: " + str(round(pd.read_csv(PROCESSED / 'features_conservation_unweighted.csv').query('valid').conservation.median(), 3))},
        {"quantity": "share of positions where >= 90% of orthologs carry the human residue", "value": (Cv.frac_human_aa >= 0.9).mean(), "note": ""},
        {"quantity": "share of positions where >= 50% of orthologs differ from human", "value": (Cv.frac_human_aa < 0.5).mean(), "note": "sense (b): low positional conservation"},
        {"quantity": "positions with >= 1 ClinVar P/LP missense", "value": int(Fd.has_plp.sum()), "note": f"{Fd.has_plp.mean():.0%} of valid positions - sense (a): spectrum heterogeneity"},
        {"quantity": "Spearman rho, conservation vs number of P/LP missense per position", "value": rho, "note": f"p = {pr:.2e}, n = {len(Fd)} positions"},
    ])
    glob.to_csv(T / "stats_F_conservation_summary.csv", index=False)
    rep += ["\n## Level 3 - F. 'Non-conserved' in the two senses\n", fmt(glob), "\nBy conservation quartile (valid positions):\n", fmt(Ftab)]

    # ---------------- level 1 recap
    rep += ["\n## Level 1 (CpG) recap, from stage 3\n", fmt(pd.read_csv(T / "cpg_enrichment.csv").drop(columns=["consequences"]))]
    (ROOT / "docs" / "stats_report.md").write_text("\n".join(rep))
    print(fmt(A.drop(columns=["type", "stat"]).iloc[:, :11])); print(fmt(C)); print(fmt(D)); print(Rg.to_string() if len(Rg) else "no significant regions")
